List<ResourceItem> getAvailableResources({
  ResourceCategory? category,
  String? policeStationId,
  double? maxDistanceKm,
  LatLng? fromLocation,
}) {
  var resources = staticResources.where((r) => r.isAvailable);

  if (category != null) {
    resources = resources.where((r) => r.category == category);
  }

  if (policeStationId != null) {
    resources = resources.where((r) => r.currentHoldingPoliceStationId == policeStationId);
  }

  if (maxDistanceKm != null && fromLocation != null) {
    resources = resources.where((r) {
      if (r.currentLocation == null) return false;
      return LatLng.distance(fromLocation, r.currentLocation!) <= maxDistanceKm;
    });
  }

  return resources.toList();
}

ResourceItem? getResourceById(String id) {
  try {
    return staticResources.firstWhere((r) => r.id == id);
  } catch (_) {
    return null;
  }
}

List<ResourceItem> getResourcesNearLocation(LatLng location, double radiusKm, {ResourceCategory? category}) {
  var resources = staticResources.where((r) {
    if (r.currentLocation == null) return false;
    if (!r.isAvailable) return false;
    if (category != null && r.category != category) return false;
    return LatLng.distance(location, r.currentLocation!) <= radiusKm;
  }).toList();

  resources.sort((a, b) {
    final distA = a.currentLocation != null ? LatLng.distance(location, a.currentLocation!) : double.infinity;
    final distB = b.currentLocation != null ? LatLng.distance(location, b.currentLocation!) : double.infinity;
    return distA.compareTo(distB);
  });

  return resources;
}